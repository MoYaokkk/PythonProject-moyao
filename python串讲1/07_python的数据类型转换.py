"""
str(x): 把指定的x转换为字符串类型(任意类型都能转换为字符串)
int(x): 把指定的x转换为整数类型(中文不能转,浮点数转换丢失精度)
float(x): 把指定的x转换为浮点数类型(中文不能转,整数转换类似乘以1.0)
"""
# str(x): 把指定的x转换为字符串类型
print(10 + 20)  # 30
print('10' + '20')  # 1020
print(str(10) + str(20))  # 1020

# int(x): 把指定的x转换为整数类型
print(int(3.14))    # 3
print(int(3.94))    # 3
# print(int('你好'))    # 报错

# float(x): 把指定的x转换为浮点数类型
print(float(3))     # 3.0
# print(float('你好'))      # 报错